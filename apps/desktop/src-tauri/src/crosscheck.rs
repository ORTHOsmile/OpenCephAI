//! The cross-check in the app (spec 2026-10-13 §6): which landmarks the voters can see. The per-case checks are parked
//! (owner PARK-FLAGS, 15 Oct), so only tests use this module; the learning record lives in `learning.rs`.
use ceph_model::catalog::builtin;

/// For each landmark any catalogue model names, the voters whose built-in catalogue map names it (not what is
/// installed), in catalogue landmark order.
pub fn coverage(voters: &[String]) -> Vec<(String, Vec<String>)> {
    let models = builtin();
    let mut order: Vec<String> = Vec::new();
    for m in &models {
        for id in m.entry.manifest["landmarkMap"].as_array().into_iter().flatten().filter_map(|v| v.as_str()) {
            if !order.iter().any(|o| o == id) { order.push(id.to_string()); }
        }
    }
    order.into_iter().map(|id| {
        let who = voters.iter().filter(|v| models.iter().any(|m| &m.entry.id == *v
            && m.entry.manifest["landmarkMap"].as_array().into_iter().flatten().any(|x| x.as_str() == Some(id.as_str())))).cloned().collect();
        (id, who)
    }).collect()
}

/// `reference/crosscheck-coverage.md`: the table, with "not checked" for a landmark fewer than two voters see.
pub fn coverage_markdown(voters: &[String]) -> String {
    let mut s = String::from("# Cross-check coverage: voters per landmark\n\nGenerated by `apps/desktop/src-tauri/src/crosscheck.rs` from the catalogue and `reference/crosscheck.json`; a test checks it. A landmark fewer than two voters detect always reads \"not checked\" (spec 2026-10-13 §6.2).\n\n| Landmark | Voters | Count | Checked |\n|---|---|---|---|\n");
    for (id, who) in coverage(voters) {
        s.push_str(&format!("| {id} | {} | {} | {} |\n", if who.is_empty() { "—".into() } else { who.join(", ") }, who.len(), if who.len() >= 2 { "yes" } else { "not checked" }));
    }
    s
}

#[cfg(test)]
mod tests {
    use super::*;
    fn voters() -> Vec<String> { ceph_infer::crosscheck::params().voters.clone() }
    #[test] fn the_voters_are_srpose_and_aariz_and_both_see_every_original_point() {
        let v = voters();
        assert_eq!(v, vec!["srpose-cldet23".to_string(), "aariz-cepha29".to_string()], "owner VOTERS-2");
        let c = coverage(&v);
        for id in ceph_model::scores::ORIGINAL_19 {
            let who = &c.iter().find(|(l, _)| l == id).unwrap_or_else(|| panic!("{id} missing")).1;
            assert_eq!(who, &v, "{id}: both voters must see every original point (spec §6.2); if not, stop and report");
        }
    }
    #[test] fn a_point_only_srpose_finds_has_one_voter() {
        let c = coverage(&voters());
        assert_eq!(c.iter().find(|(l, _)| l == "Ba").map(|(_, w)| w.clone()), Some(vec!["srpose-cldet23".to_string()]));
    }
    #[test] fn the_committed_coverage_file_is_current() {
        let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../reference/crosscheck-coverage.md");
        let now = coverage_markdown(&voters());
        if std::env::var("UPDATE_COVERAGE").as_deref() == Ok("1") { std::fs::write(&path, &now).unwrap(); }
        assert_eq!(std::fs::read_to_string(&path).expect("run once with UPDATE_COVERAGE=1"), now);
    }
}
