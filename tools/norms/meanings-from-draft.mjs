// Writes packages/analyses/src/norms/meanings.ts from the owner-approved docs/norms/meanings-draft.md (ticked rows only).
// Run from the repo root: node tools/norms/meanings-from-draft.mjs   (meanings.test.ts keeps the two equal).
import { readFileSync, writeFileSync } from 'fs';
const rows = readFileSync('docs/norms/meanings-draft.md', 'utf8').split('\n').filter((l) => /^\| ☑ \| \d/.test(l))
  .map((l) => l.split('|').map((x) => x.trim())).map((c) => [c[3], { abbr: c[5], high: c[6], low: c[7] }]);
const body = rows.map(([id, m]) => `  ${id}: ${JSON.stringify(m)},`).join('\n');
writeFileSync('packages/analyses/src/norms/meanings.ts', `// GENERATED by tools/norms/meanings-from-draft.mjs from docs/norms/meanings-draft.md — do not edit by hand.
/** Owner MEANING-APPROVE (16 Oct 2026): the approved default wording per measurement — a short name (abbr) and the
 *  clinical term for a value above (high) and below (low) the norm's mean. Each clinician can change high/low in
 *  Settings › Meanings (MEANING-PER-CLINICIAN). meanings.test.ts keeps this equal to the approved document. */
export interface Meaning { abbr: string; high: string; low: string }
export const DEFAULT_MEANINGS: Record<string, Meaning> = {
${body}
};
`);
console.log(`wrote ${rows.length} meanings`);
